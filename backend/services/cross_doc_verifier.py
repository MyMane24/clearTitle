def run_cross_doc_verification(documents: list[dict]) -> dict:
    """
    Run cross-document verification on all structured documents.
    Enhanced with statute RAG, few-shot retrieval, extended checks.
    """
    if not GROQ_API_KEY:
        return _fallback_verification(documents)

    # ── Retrieve few-shot corrections from human feedback ──────────────
    doc_types_in_bundle = {d.get("document_type") for d in documents if d.get("document_type")}
    few_shot_examples = ""
    for dt in doc_types_in_bundle:
        corrections = retrieve_corrections(dt)
        if corrections:
            few_shot_examples += format_few_shot_examples(corrections) + "\n"

    # ── Determine property type for expected-docs check ────────────────
    property_type = _detect_property_type(documents)

    # ── Run extended deterministic checks ──────────────────────────────
    deterministic_findings = []
    deterministic_findings.extend(_check_chain_of_title_years(documents))
    deterministic_findings.extend(_check_authority_to_sign(documents))
    deterministic_findings.extend(_check_inheritance_succession(documents))
    deterministic_findings.extend(_check_valuation_consistency(documents))
    deterministic_findings.extend(_check_rera_applicability(documents, property_type))
    deterministic_findings.extend(_check_document_recency(documents))
    deterministic_findings.extend(_check_expected_missing_docs(documents, property_type))

    _http_client = httpx.Client(timeout=httpx.Timeout(120.0, connect=30.0))
    client = Groq(api_key=GROQ_API_KEY, http_client=_http_client)

    doc_summaries = []
    for doc in documents:
        sd = doc.get("structured_json", {}) or {}
        vn = doc.get("verification_notes", []) or []
        summary = {
            "doc_id": doc.get("doc_id"),
            "document_type": doc.get("document_type"),
            "structured_fields": _compact_fields(sd),
            "per_doc_verification_notes": vn,
        }
        doc_summaries.append(summary)

    input_payload = {
        "total_documents": len(documents),
        "deterministic_findings": deterministic_findings,
        "documents": doc_summaries,
    }
    input_text = json.dumps(input_payload, indent=2, ensure_ascii=False)

    user_prompt = (
        "Review the following property case bundle and produce a verification report.\n\n"
        "NOTE: Deterministic checks have already been run. The findings are provided for context.\n"
        "Integrate them into your analysis but focus on cross-document reasoning.\n\n"
        f"{few_shot_examples}\n"
        f"CASE DOCUMENTS:\n{input_text}\n\n"
        "Return ONLY valid JSON matching the specified output format."
    )

    start = time.time()

    for model in [GROQ_MODEL, FALLBACK_GROQ_MODEL]:
        try:
            acquired = groq_limiter.wait_and_acquire()
            if not acquired:
                logger.warning("Rate limit wait timeout for cross-doc verifier")

            response = client.chat.completions.create(
                model=model,
                messages=[
                    {"role": "system", "content": CROSS_DOC_SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=0.1,
                max_tokens=8000,
                response_format={"type": "json_object"},
            )
            latency = int((time.time() - start) * 1000)
            raw = response.choices[0].message.content.strip()

            try:
                result = json.loads(raw)
            except json.JSONDecodeError:
                m = re.search(r'```(?:json)?\s*([\s\S]*?)\s*```', raw)
                if m:
                    result = json.loads(m.group(1))
                else:
                    raise

            usage = response.usage
            input_tokens = usage.prompt_tokens if usage else len(input_text) // 4
            output_tokens = usage.completion_tokens if usage else len(raw) // 4

            result.setdefault("verdict", "MANUAL_REVIEW")
            result.setdefault("findings", [])
            result.setdefault("final_report", raw if not result.get("final_report") else result["final_report"])

            # Merge deterministic findings with LLM findings
            llm_findings = result.get("findings", [])
            all_findings = deterministic_findings + llm_findings

            # Deduplicate by type + summary
            seen = set()
            unique_findings = []
            for f in all_findings:
                key = (f.get("type", ""), f.get("summary", "")[:100])
                if key not in seen:
                    seen.add(key)
                    unique_findings.append(f)
            all_findings = unique_findings

            # ── Compute composite risk score ────────────────────────────
            risk_result = compute_risk_score(all_findings)
            result["risk_score"] = risk_result["risk_score"]
            result["risk_score_details"] = risk_result
            result["findings"] = all_findings

            # Override verdict with risk-based verdict if more conservative
            if risk_result["verdict"] == "FLAGGED" and result.get("verdict") != "FLAGGED":
                result["verdict"] = "FLAGGED"
            elif risk_result["verdict"] == "MANUAL_REVIEW" and result.get("verdict") == "PASS":
                result["verdict"] = "MANUAL_REVIEW"

            # ── Ensure legal opinion format in final_report ─────────────
            result["final_report"] = _ensure_legal_opinion_format(
                result.get("final_report", ""), result["verdict"],
                risk_result, all_findings,
            )

            result["_analytics"] = {
                "model": model,
                "input_tokens": input_tokens,
                "output_tokens": output_tokens,
                "latency_ms": latency,
                "cost_usd": (input_tokens / 1_000_000 * 0.59) + (output_tokens / 1_000_000 * 0.79),
                "deterministic_findings_count": len(deterministic_findings),
            }

            LLMCallTracker.record(
                provider="groq", model=model, doc_type="cross_doc_verifier",
                input_tokens=input_tokens, output_tokens=output_tokens,
                cached_tokens=0, latency_ms=latency,
                cost_usd=result["_analytics"]["cost_usd"],
                retry_count=0, status="success",
            )

            return result

        except Exception as e:
            logger.error("Cross-doc verification with %s failed: %s", model, e)
            continue

    return _fallback_verification(documents, deterministic_findings)


