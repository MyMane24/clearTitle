def _ensure_legal_opinion_format(report_text: str, verdict: str,
                                   risk_result: dict, findings: list[dict]) -> str:
    """Ensure final_report follows the exact legal opinion format requested by the user."""
    # If report already has the requested exact structure, return as-is
    if "Executive Summary" in report_text and "Documents Reviewed" in report_text and "Final Recommendation" in report_text:
        return report_text

    critical_count = sum(1 for f in findings if f.get("severity") in ("critical", "high"))
    med_count = sum(1 for f in findings if f.get("severity") == "medium")
    low_count = sum(1 for f in findings if f.get("severity") == "low")

    # Detect unique documents involved
    doc_types = set()
    for f in findings:
        for d in f.get("doc_ids", []):
            doc_types.add(d)
    doc_count = len(doc_types) if doc_types else 1

    # Overall Risk
    risk_score = risk_result.get("risk_score", 0)
    if risk_score >= 70:
        overall_risk = "High Risk"
    elif risk_score >= 40:
        overall_risk = "Medium Risk"
    else:
        overall_risk = "Low Risk"

    # Major Risks
    major_risks = []
    for f in findings:
        if f.get("severity") in ("critical", "high"):
            title = f.get("title") or f.get("summary") or f.get("type", "")
            if title and title not in major_risks:
                major_risks.append(title)

    # Missing Documents
    missing_docs = []
    for f in findings:
        ftype = (f.get("type") or "").upper()
        if ftype in ("MISSING_DOCUMENT", "MISSING_EXPECTED_DOCUMENT"):
            title = f.get("title") or f.get("summary") or ""
            # Strip "Missing" prefix if present for clean bullet list
            clean_title = re.sub(r'^[Mm]issing\s+', '', title).replace(" expected due diligence documents for apartment property", "").replace(" expected due diligence documents for house property", "").replace(" expected due diligence documents for land property", "")
            if clean_title and clean_title not in missing_docs:
                missing_docs.append(clean_title)

    # Recommended Actions
    actions = []
    for f in findings:
        steps = f.get("verification_steps") or []
        if isinstance(steps, str):
            steps = [steps]
        # Fallback to suggestion
        if not steps and f.get("suggestion"):
            steps = [f["suggestion"]]
        for step in steps:
            if step and step not in actions:
                actions.append(step)
            if len(actions) >= 8:
                break

    # Final Recommendation
    final_rec = "SAFE TO PROCEED" if verdict == "PASS" else "NOT SAFE TO PROCEED"

    # Final Reason
    if verdict == "PASS":
        final_reason = "No critical or high-severity title risks were detected across the reviewed property documents."
    else:
        final_reason = f"Property ownership cannot yet be confirmed because multiple title-related issues ({critical_count} critical/high findings) remain unresolved."

    lines = []
    lines.append("Executive Summary")
    lines.append(f"Property verification completed. A comprehensive title search and due diligence review has been performed on the provided case bundle.")
    lines.append("")

    lines.append("Documents Reviewed")
    lines.append(str(doc_count))
    lines.append("")

    lines.append("Total Findings")
    lines.append(str(len(findings)))
    lines.append("")

    lines.append("Critical")
    lines.append(str(critical_count))
    lines.append("")

    lines.append("Medium")
    lines.append(str(med_count))
    lines.append("")

    lines.append("Low")
    lines.append(str(low_count))
    lines.append("")

    lines.append("Overall Risk")
    lines.append(overall_risk)
    lines.append("")

    lines.append("Major Risks")
    if major_risks:
        for r in major_risks:
            lines.append(f"• {r}")
    else:
        lines.append("• None")
    lines.append("")

    lines.append("Missing Documents")
    if missing_docs:
        for d in missing_docs:
            lines.append(f"• {d}")
    else:
        lines.append("• None")
    lines.append("")

    lines.append("Recommended Actions")
    if actions:
        for idx, act in enumerate(actions, 1):
            lines.append(f"{idx}. {act}")
    else:
        lines.append("1. None required; proceed with standard transaction safeguards.")
    lines.append("")

    lines.append("Final Recommendation")
    lines.append(final_rec)
    lines.append("")

    lines.append("Final Reason")
    lines.append(final_reason)

    return "\n".join(lines)


def _compact_fields(sd: dict) -> dict:
    """Extract only the fields that matter for cross-document checks from structured data."""
    compact = {}

    if isinstance(sd, dict):
        fm = sd.get("file_metadata") or sd.get("document_metadata") or {}
        compact["registration_number"] = fm.get("registration_number")
        compact["execution_date"] = fm.get("execution_date")
        compact["registration_date"] = fm.get("registration_date")
        compact["issuing_office"] = fm.get("issuing_office")

        ps = sd.get("property_schedule") or sd.get("property_identification") or {}
        compact["survey_number"] = ps.get("survey_number") or ps.get("city_survey_number")
        compact["cts_number"] = ps.get("cts_number")
        compact["pid"] = sd.get("consumer_details", {}).get("pid") if isinstance(sd.get("consumer_details"), dict) else None

        sc = sd.get("search_criteria") or {}
        compact["search_start_date"] = sc.get("search_start_date") or fm.get("search_start_date")
        compact["search_end_date"] = sc.get("search_end_date") or fm.get("search_end_date")

        fin = sd.get("financial_summary") or {}
        compact["consideration"] = fin.get("declared_consideration_amount")
        compact["stamp_duty"] = fin.get("stamp_duty_paid_amount") or fin.get("stamp_duty_amount")

        parties = sd.get("parties") or {}
        vendors = parties.get("vendors") or []
        purchasers = parties.get("purchasers") or []
        compact["vendor_names"] = [v.get("entity_name") for v in vendors if isinstance(v, dict)]
        compact["purchaser_names"] = [p.get("entity_name") for p in purchasers if isinstance(p, dict)]

        ledger = sd.get("historical_ledger") or sd.get("transactions") or []
        if ledger:
            compact["historical_ledger"] = []
            for tx in ledger:
                if not isinstance(tx, dict):
                    continue
                parties = tx.get("parties") or {}
                vendors = parties.get("vendors") or []
                purchasers = parties.get("purchasers") or []
                prop = tx.get("property_details") or {}
                fin = tx.get("financials") or {}
                compact["historical_ledger"].append({
                    "tx_index": tx.get("transaction_index"),
                    "execution_date": tx.get("execution_date"),
                    "doc_reference": tx.get("registration_reference"),
                    "type": tx.get("transaction_type"),
                    "consideration": fin.get("consideration_amount"),
                    "vendors": vendors,
                    "purchasers": purchasers,
                    "survey_no": prop.get("survey_no") or prop.get("survey_number") or prop.get("plot_no"),
                    "cts_no": prop.get("cts_no") or prop.get("cts_number") or prop.get("pid_no"),
                    "description": prop.get("description"),
                })

        holders = sd.get("holders") or []
        if holders:
            compact["holder_names"] = [h.get("name") for h in holders if isinstance(h, dict)]

        gv = sd.get("guidance_value") or {}
        if gv:
            compact["guidance_value"] = gv.get("value")
            compact["guidance_value_order_date"] = gv.get("order_date")

        # ── Land-specific extractions for cross-document checks ──
        
        # Extent from RTC
        ld = sd.get("land_details") or {}
        ext = ld.get("extent_details") or {}
        if ext.get("net_area_acres_gunthas"):
            compact["rtc_net_area"] = ext.get("net_area_acres_gunthas")
            compact["rtc_total_extent"] = ext.get("total_extent_acres_gunthas")
            compact["survey_number"] = ld.get("survey_number")
            compact["hissa_number"] = ld.get("hissa_number")
        
        # Owners from RTC Column 9
        owners = sd.get("owners_column_9") or []
        if owners:
            compact["rtc_owners"] = [o.get("owner_name") for o in owners if isinstance(o, dict)]
            compact["rtc_owner_extents"] = [o.get("extent_owned_acres_gunthas") for o in owners if isinstance(o, dict)]
            compact["rtc_owner_acquisitions"] = [o.get("acquisition_mode_column_10") for o in owners if isinstance(o, dict)]

        # Liabilities from RTC Column 11
        rights_liab = sd.get("other_rights_and_liabilities_column_11") or {}
        if rights_liab.get("liabilities_loans"):
            compact["rtc_liabilities"] = rights_liab.get("liabilities_loans")
        if rights_liab.get("conditions_notes"):
            compact["rtc_conditions"] = rights_liab.get("conditions_notes")

        # NA Conversion Details (CONVERSION_ORDER)
        prop_det = sd.get("property_details") or {}
        if prop_det.get("converted_extent_acres_gunthas"):
            compact["converted_extent"] = prop_det.get("converted_extent_acres_gunthas")
            compact["converted_purpose"] = prop_det.get("converted_purpose")
            compact["conversion_order_number"] = fm.get("order_number")
            compact["conversion_order_date"] = fm.get("order_date")
            compact["survey_number"] = prop_det.get("survey_number")

        # Mutation Details (MUTATION)
        tx_details = sd.get("transaction_details") or []
        if tx_details:
            compact["mutated_transactions"] = [
                {
                    "new_survey": tx.get("new_survey_number"),
                    "new_extent": tx.get("new_extent_acres_gunthas"),
                    "owner": tx.get("owner_name"),
                }
                for tx in tx_details if isinstance(tx, dict)
            ]
            compact["mutation_number"] = fm.get("mutation_number")
            compact["mutation_acquisition_mode"] = fm.get("acquisition_mode")

        # CDP Plan Details (CDP_PLAN)
        if sd.get("zoning_classification"):
            compact["cdp_zoning"] = sd.get("zoning_classification")
            compact["cdp_approval_number"] = fm.get("approval_number")
            compact["cdp_approval_date"] = fm.get("approval_date")
            compact["cdp_surveys_covered"] = fm.get("survey_numbers_covered")

    return compact


def _fallback_verification(documents: list[dict],
                            deterministic_findings: list[dict] | None = None) -> dict:
    """Simple deterministic fallback when LLM is unavailable."""
    findings = list(deterministic_findings or [])
    doc_types = {doc.get("document_type"): doc for doc in documents if doc.get("document_type")}

    critical = ["SALE_DEED", "ENCUMBRANCE_CERTIFICATE"]
    for c in critical:
        if c not in doc_types:
            findings.append({
                "type": "MISSING_DOCUMENT", "severity": "high",
                "doc_ids": [c], "summary": f"Missing {c} — critical for title verification",
                "legal_detail": "A complete title due diligence requires both a deed and EC.",
                "suggestion": f"Upload {c} to enable complete verification.", "confidence": 1.0,
            })

    risk_result = compute_risk_score(findings)
    verdict = risk_result["verdict"]

    report = _ensure_legal_opinion_format(
        f"Cross-doc verification run in fallback mode (Groq API unavailable). "
        f"Reviewed {len(documents)} documents via deterministic checks only.",
        verdict, risk_result, findings,
    )

    return {
        "verdict": verdict,
        "risk_score": risk_result["risk_score"],
        "risk_score_details": risk_result,
        "findings": findings,
        "final_report": report,
        "_analytics": {"model": "fallback", "input_tokens": 0, "output_tokens": 0, "latency_ms": 0, "cost_usd": 0},
    }
